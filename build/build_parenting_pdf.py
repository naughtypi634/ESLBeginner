# ---------------------------------------------------------------- helpers
def esc(s: str) -> str:
    return (
        s.replace("\\", r"\textbackslash{}")
        .replace("{", r"\{")
        .replace("}", r"\}")
        .replace("$", r"\$")
        .replace("&", r"\&")
        .replace("#", r"\#")
        .replace("_", r"\_")
        .replace("%", r"\%")
        .replace("^", r"\textasciicircum{}")
        .replace("~", r"\textasciitilde{}")
    )


def raw(latex: str) -> str:
    return "```{=latex}\n" + latex + "\n```\n\n"


def T_title():
    return raw(f"\\esltitle{{{esc(TITLE)}}}")


def T_section(num: str, cn: str, en: str):
    return raw(f"\\eslsection{{{esc(num)}}}{{{esc(cn)}}}{{{esc(en)}}}")


def T_pair(en: str, cn: str):
    # 每对 EN/CN 放进 minipage：整对作为一个不可分页的块，中英文永不跨页分离。
    return raw(
        f"\\par\\vspace{{2pt}}\\noindent\\begin{{minipage}}[t]{{\\linewidth}}"
        f"{{\\bodyfont {esc(en)}}}\\par\\vspace{{1.5pt}}"
        f"{{\\color{{muted}}\\footnotesize {esc(cn)}}}"
        f"\\end{{minipage}}\\par\\vspace{{4.5pt}}"
    )


